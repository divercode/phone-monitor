"""生成示例 .cube LUT（用于手动导入 App 验证 LUT 管线）。

产出：
  samples/identity-17.cube     恒等 LUT：套用后画面应完全不变 → 用于验证管线正确性
  samples/demo-warm-look.cube  轻微 S 曲线 + 暖调外观 → 用于验证视觉效果

注意：这里不是 S-Log3 还原 LUT。正式素材请用索尼官方 LUT
（Alpha Universe LUT Gallery 或随相机/固件发布的 S-Gamut3.Cine/S-Log3 → Rec.709）。
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "samples")
SIZE = 17


def clamp01(v):
    return min(max(v, 0.0), 1.0)


def identity(r, g, b):
    return r, g, b


def smoothstep(v):
    return v * v * (3.0 - 2.0 * v)


def warm_look(r, g, b):
    """柔和对比 + 轻微暖调。"""
    def curve(v):
        v = clamp01(v)
        return clamp01(0.55 * v + 0.45 * smoothstep(v))

    return curve(r) * 1.04, curve(g) * 1.00, curve(b) * 0.94


def write_cube(path, title, fn):
    lines = [
        f"# {title}",
        "# generated by .tools/gen_sample_luts.py for PhoneMonitor testing",
        f'TITLE "{title}"',
        f"LUT_3D_SIZE {SIZE}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
        "",
    ]
    # .cube 顺序：R 变化最快
    for b in range(SIZE):
        for g in range(SIZE):
            for r in range(SIZE):
                rgb = (r / (SIZE - 1), g / (SIZE - 1), b / (SIZE - 1))
                out = fn(*rgb)
                lines.append("%.6f %.6f %.6f" % tuple(clamp01(c) for c in out))
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return len(lines) - 7


def self_check_identity():
    for i in range(256):
        v = i / 255.0
        r, g, b = identity(v, v, v)
        assert r == g == b == v
    print("  identity: 端点/单调性 OK（逐通道原样返回）")


def self_check_warm():
    prev = -1.0
    for i in range(256):
        v = i / 255.0
        out = warm_look(v, v, v)[0]
        assert prev <= out + 1e-6, f"warm look 非单调 @ {v}"
        prev = out
    assert abs(warm_look(0, 0, 0)[0]) < 1e-3
    assert abs(clamp01(warm_look(1, 1, 1)[0]) - 1.0) < 1e-3
    print("  warm look: 黑=0 白=1 单调性 OK")


def main():
    os.makedirs(OUT, exist_ok=True)
    print("自检：")
    self_check_identity()
    self_check_warm()

    p1 = os.path.join(OUT, "identity-17.cube")
    p2 = os.path.join(OUT, "demo-warm-look.cube")
    n1 = write_cube(p1, "Identity 17x17x17 (pipeline test)", identity)
    n2 = write_cube(p2, "Warm look (demo)", warm_look)
    print(f"已生成 {os.path.relpath(p1, ROOT)}（{n1} 条数据）")
    print(f"已生成 {os.path.relpath(p2, ROOT)}（{n2} 条数据）")


if __name__ == "__main__":
    main()
