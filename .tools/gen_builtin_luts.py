"""生成内置 LUT（打包进 APK 的 assets/luts/）。

内置（只读）LUT 是自研外观，不包含索尼官方版权文件；官方 S-Log3 还原 LUT
请自行放入 app/src/main/assets/luts/ 后重新构建（见 README）。

用法: python .tools/gen_builtin_luts.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "app", "src", "main", "assets", "luts")
SIZE = 17


def clamp01(v):
    return min(max(v, 0.0), 1.0)


def smoothstep(v):
    return v * v * (3.0 - 2.0 * v)


def identity(r, g, b):
    return r, g, b


def warm_film(r, g, b):
    def curve(v):
        v = clamp01(v)
        return clamp01(0.55 * v + 0.45 * smoothstep(v))

    # 端点保持 0/1：用乘性偏色而不是整体缩放
    rc = clamp01(curve(r) * (1.0 + 0.06 * (1.0 - curve(r))))
    bc = clamp01(curve(b) * (1.0 - 0.15 * (1.0 - curve(b))))
    return rc, curve(g), bc


def teal_orange(r, g, b):
    l = clamp01(0.299 * r + 0.587 * g + 0.114 * b)
    t = 4.0 * l * (1.0 - l)  # 中间调权重，端点自动归零
    rc = clamp01(r + 0.12 * t * l)        # 中高调偏暖
    bc = clamp01(b + 0.12 * t * (1.0 - l))  # 暗部偏青
    return rc, clamp01(g), bc


def mono(r, g, b):
    l = clamp01(0.299 * r + 0.587 * g + 0.114 * b)
    y = clamp01(0.4 * l + 0.6 * smoothstep(l))
    return y, y, y


LUTS = [
    ("identity-17", "Identity（管线自测）", identity),
    ("warm-film-17", "Warm Film（暖调胶片）", warm_film),
    ("teal-orange-17", "Teal & Orange（青橙）", teal_orange),
    ("mono-17", "Mono Contrast（黑白）", mono),
]


def write_cube(path, title, fn):
    lines = [
        f'# {title}',
        "# built-in LUT generated by PhoneMonitor",
        f'TITLE "{title}"',
        f"LUT_3D_SIZE {SIZE}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
        "",
    ]
    for b in range(SIZE):
        for g in range(SIZE):
            for r in range(SIZE):
                out = fn(r / (SIZE - 1), g / (SIZE - 1), b / (SIZE - 1))
                lines.append("%.6f %.6f %.6f" % tuple(clamp01(c) for c in out))
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def self_check(name, fn):
    # 黑点/白点大致保持（黑白 LUT 也成立）
    blk = fn(0.0, 0.0, 0.0)
    wht = fn(1.0, 1.0, 1.0)
    assert all(abs(c) < 1e-3 for c in blk), f"{name} 黑点不为 0: {blk}"
    assert all(abs(c - 1.0) < 2e-2 for c in wht), f"{name} 白点不为 1: {wht}"
    print(f"  {name}: 黑点/白点自检 OK")


def main():
    os.makedirs(OUT, exist_ok=True)
    print("自检：")
    for name, _, fn in LUTS:
        self_check(name, fn)
    for name, title, fn in LUTS:
        path = os.path.join(OUT, name + ".cube")
        write_cube(path, title, fn)
        print("wrote", os.path.relpath(path, ROOT),
              f"({os.path.getsize(path) // 1024} KB)")


if __name__ == "__main__":
    main()
